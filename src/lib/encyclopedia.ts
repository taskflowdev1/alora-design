// The UI encyclopedia: the rules Alora Design's components follow and our coding agents check before review.
// Written in our own words; each rule credits the sources it draws on (SOURCES, at the bottom). Shown at /encyclopedia,
// and turned into docs/ui-checklist.md and /ui-checklist.md by checklistMarkdown() below.

/** must: blocks review. should: the default unless there's a stated reason. showcase: decoration, allowed only on showcase and demo pages. */
export type Level = "must" | "should" | "showcase";
/** Where a rule applies: desktop screens (pointer, hover, keyboard), phone screens (touch), or both. */
export type Platform = "desktop" | "mobile" | "both";

export interface Category {
  id: string;
  title: string;
}

export interface Rule {
  /** Stable id, "<area>.<slug>". Agents cite it in reviews. */
  id: string;
  category: string;
  level: Level;
  title: string;
  /** The rule in one or two sentences. */
  rule: string;
  why: string;
  /** Concrete values: classes, tokens, CSS. */
  how: string;
  /** How an agent verifies it: a grep, a computed style, a Playwright step, or a visual check. */
  check: string;
  /** Where the common advice differs, what it says and why we do otherwise. */
  context?: string;
  /** Source ids from SOURCES. Empty: an Alora Design rule with no outside source. */
  sources: string[];
  /** Set only to override the default (platformOf): the Mobile category is "mobile", DESKTOP_RULES "desktop", the rest "both". */
  platform?: Platform;
}

export interface Source {
  id: string;
  name: string;
  url: string;
  licence: string;
}

